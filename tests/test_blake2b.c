CT_TEST(blake2b_streaming_matches_one_shot)
{
    uint8_t msg[300];
    uint8_t once[64];
    uint8_t part[64];
    cairn_blake2b_state st;
    size_t i;

    for (i = 0; i < sizeof msg; i++) msg[i] = (uint8_t)(i * 7u + 1u);

    CT_ASSERT_EQ_INT(cairn_hash(once, sizeof once, msg, sizeof msg), CAIRN_OK);
    CT_ASSERT_EQ_INT(cairn_blake2b_init(&st, 64, NULL, 0), CAIRN_OK);
    CT_ASSERT_EQ_INT(cairn_blake2b_update(&st, msg, 1), CAIRN_OK);
    CT_ASSERT_EQ_INT(cairn_blake2b_update(&st, msg + 1, 128), CAIRN_OK);
    CT_ASSERT_EQ_INT(cairn_blake2b_update(&st, msg + 129, 171), CAIRN_OK);
    CT_ASSERT_EQ_INT(cairn_blake2b_final(&st, part, sizeof part), CAIRN_OK);
    CT_ASSERT_MEM_EQ(part, once, sizeof once);
}

CT_TEST(blake2b_rejects_bad_output_size)
{
    uint8_t out[65];
    CT_ASSERT_EQ_INT(cairn_hash(out, 0, "x", 1), CAIRN_ERR_ARG);
    CT_ASSERT_EQ_INT(cairn_hash(out, 65, "x", 1), CAIRN_ERR_ARG);
    CT_ASSERT_EQ_INT(cairn_hash(NULL, 32, "x", 1), CAIRN_ERR_ARG);
}

void ct_reg_blake2b(void)
{
    CT_REG(blake2b_512_of_abc);
    CT_REG(blake2b_512_of_empty);
    CT_REG(blake2b_keyed_matches_reference);
    CT_REG(blake2b_streaming_matches_one_shot);
    CT_REG(blake2b_rejects_bad_output_size);
}